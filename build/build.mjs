// Static build for SRAL LIMS: copies app/src into dist/, cache-busts assets, substitutes
// index.html's %% placeholders, and generates worker/site-config.js. No framework, no
// dependencies — same house style as foodwatertesting.com/Prachar (see build/README there).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const ROOT = path.dirname(new URL(import.meta.url).pathname);
const SRC = path.join(ROOT, '..', 'app', 'src');
const DIST = path.join(ROOT, '..', 'dist');
const CFG = JSON.parse(fs.readFileSync(path.join(ROOT, 'config.json'), 'utf8'));

fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(path.join(DIST, 'assets'), { recursive: true });

const hash = (s) => crypto.createHash('sha256').update(s).digest('hex').slice(0, 10);

const appCss = fs.readFileSync(path.join(SRC, 'app.css'), 'utf8');
const apiJs = fs.readFileSync(path.join(SRC, 'lib', 'api.js'), 'utf8');
const pdfJs = fs.readFileSync(path.join(SRC, 'lib', 'pdf.js'), 'utf8');
const appJs = fs.readFileSync(path.join(SRC, 'app.js'), 'utf8');

fs.writeFileSync(path.join(DIST, 'assets', 'app.css'), appCss);
fs.writeFileSync(path.join(DIST, 'assets', 'api.js'), apiJs);
fs.writeFileSync(path.join(DIST, 'assets', 'pdf.js'), pdfJs);
fs.writeFileSync(path.join(DIST, 'assets', 'app.js'), appJs);

let html = fs.readFileSync(path.join(SRC, 'index.html'), 'utf8');
html = html
  .replace('%%CSSVER%%', hash(appCss))
  .replace('%%APIVER%%', hash(apiJs))
  .replace('%%PDFVER%%', hash(pdfJs))
  .replace('%%APPVER%%', hash(appJs))
  .replace('%%CONFIG_JSON%%', JSON.stringify({ supabaseUrl: CFG.supabaseUrl, publishableKey: CFG.publishableKey }));
fs.writeFileSync(path.join(DIST, 'index.html'), html);

// brand mark favicon — same teal "S" as foodwatertesting.com, recognisably the same lab
fs.writeFileSync(path.join(DIST, 'favicon.svg'),
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="7" fill="#0b6b6f"/>' +
  '<text x="16" y="23" font-family="Georgia,serif" font-size="19" font-weight="700" fill="#fff" text-anchor="middle">S</text></svg>\n');

// internal tool: never indexed, never crawled
fs.writeFileSync(path.join(DIST, 'robots.txt'), 'User-agent: *\nDisallow: /\n');

// the Worker only needs the Supabase URL, to build its Content-Security-Policy
fs.writeFileSync(path.join(ROOT, '..', 'worker', 'site-config.js'),
  '// Generated by build/build.mjs — do not edit by hand.\nexport default ' + JSON.stringify({ supabaseUrl: CFG.supabaseUrl }, null, 2) + ';\n');

console.log('built: index.html + 4 assets, favicon, robots.txt, worker/site-config.js');
